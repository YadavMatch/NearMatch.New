export function getLocalDateKey(date: Date = new Date()): string {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

export function getLocalEpochDay(date: Date = new Date()): number {
  const utcMidnightMs = Date.UTC(
    date.getFullYear(),
    date.getMonth(),
    date.getDate()
  );
  return Math.floor(utcMidnightMs / 86_400_000);
}

export function getDailyPulseQuote(date: Date = new Date()): DailyPulseQuote {
  const total = DAILY_PULSE_QUOTES.length;
  const epochDay = getLocalEpochDay(date);
  const index = ((epochDay % total) + total) % total;
  return DAILY_PULSE_QUOTES[index];
}

export function formatPulseDateLabel(date: Date = new Date()): string {
  return date.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
  });
}
